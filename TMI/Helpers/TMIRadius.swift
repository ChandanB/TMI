import SwiftUI

/// Design system border radius constants
struct TMIRadius {
    /// No radius (square corners) - 0 points
    static let none: CGFloat = 0
    
    /// Extra small radius - 2 points
    static let xs: CGFloat = 2
    
    /// Small radius - 4 points
    static let sm: CGFloat = 4
    
    /// Medium radius - 8 points
    static let md: CGFloat = 8
    
    /// Large radius - 12 points
    static let lg: CGFloat = 12
    
    /// Extra large radius - 16 points
    static let xl: CGFloat = 16
    
    /// Full radius (circular) - 9999 points
    static let full: CGFloat = 9999
}
